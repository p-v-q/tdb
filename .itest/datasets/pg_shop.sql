-- 3. sales schema (partitioned orders)
-- =====================================================================
CREATE TABLE sales.orders (
    id               bigint NOT NULL,
    customer_id      bigint NOT NULL REFERENCES public.customers(id),
    order_no         text NOT NULL,
    status           public.order_status NOT NULL DEFAULT 'pending',
    total            public.positive_money NOT NULL DEFAULT 0,
    currency         char(3) NOT NULL DEFAULT 'USD',
    ordered_at       timestamptz NOT NULL,
    shipping_address jsonb,
    notes            text,
    coupon_code      text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (id, ordered_at)
) PARTITION BY RANGE (ordered_at);
COMMENT ON TABLE sales.orders IS '500k orders range-partitioned by month on ordered_at (2024-01 .. 2025-12)';
COMMENT ON COLUMN sales.orders.ordered_at IS 'Partition key (monthly range)';

DO $$
DECLARE
    m date := DATE '2024-01-01';
BEGIN
    WHILE m < DATE '2026-01-01' LOOP
        EXECUTE format(
            'CREATE TABLE sales.orders_%s PARTITION OF sales.orders FOR VALUES FROM (%L) TO (%L)',
            to_char(m, 'YYYY_MM'), m, m + interval '1 month');
        m := m + interval '1 month';
    END LOOP;
END
$$;
CREATE TABLE sales.orders_default PARTITION OF sales.orders DEFAULT;

CREATE TABLE sales.order_items (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id         bigint NOT NULL,
    order_ordered_at timestamptz NOT NULL,
    product_id       bigint NOT NULL REFERENCES public.products(id),
    quantity         integer NOT NULL CHECK (quantity BETWEEN 1 AND 50),
    unit_price       numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    discount         numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 100),
    line_total       numeric(14,2) GENERATED ALWAYS AS
        (round(quantity * unit_price * (1 - discount / 100), 2)) STORED,
    FOREIGN KEY (order_id, order_ordered_at)
        REFERENCES sales.orders (id, ordered_at) ON DELETE CASCADE
);
COMMENT ON TABLE sales.order_items IS '1.5M order lines; generated stored line_total, composite FK to partitioned orders';

CREATE TABLE sales.payments (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id         bigint NOT NULL,
    order_ordered_at timestamptz NOT NULL,
    method           public.payment_method NOT NULL,
    amount           public.positive_money NOT NULL,
    provider_ref     text NOT NULL,
    paid_at          timestamptz NOT NULL,
    raw_response     jsonb,
    FOREIGN KEY (order_id, order_ordered_at)
        REFERENCES sales.orders (id, ordered_at) ON DELETE CASCADE
);
COMMENT ON TABLE sales.payments IS '500k payments; enum method, jsonb provider response';

CREATE TABLE sales.order_audit (
    audit_id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id    bigint NOT NULL,
    old_status  public.order_status,
    new_status  public.order_status,
    changed_at  timestamptz NOT NULL DEFAULT now(),
    changed_by  text NOT NULL DEFAULT current_user
);
COMMENT ON TABLE sales.order_audit IS 'Audit trail populated by the orders AFTER UPDATE trigger';

CREATE TABLE sales.invoices (
    invoice_no bigint NOT NULL DEFAULT nextval('sales.invoice_seq') PRIMARY KEY,
    order_id   bigint NOT NULL,
    amount     public.positive_money NOT NULL,
    issued_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sales.order_tags (
    order_id bigint NOT NULL,
    tag      text NOT NULL,
    PRIMARY KEY (order_id, tag)
);

