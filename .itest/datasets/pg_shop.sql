CREATE FUNCTION analytics.fn_customer_lifetime(p_customer_id bigint)
RETURNS numeric
LANGUAGE sql STABLE
AS $$
    SELECT coalesce(sum(o.total), 0)::numeric(14,2)
    FROM sales.orders o
    WHERE o.customer_id = p_customer_id
$$;

CREATE FUNCTION analytics.fn_revenue_between(p_from timestamptz, p_to timestamptz)
RETURNS numeric
LANGUAGE sql STABLE
AS $$
    SELECT coalesce(sum(total), 0)::numeric(14,2)
    FROM sales.orders
    WHERE ordered_at >= p_from AND ordered_at < p_to
      AND status IN ('paid', 'shipped', 'delivered')
$$;

CREATE FUNCTION analytics.fn_orders_by_status(p_status public.order_status)
RETURNS TABLE (order_id bigint, customer_email text, total numeric, ordered_at timestamptz)
LANGUAGE plpgsql STABLE
AS $$
BEGIN
    RETURN QUERY
        SELECT o.id, c.email::text, o.total::numeric, o.ordered_at
        FROM sales.orders o
        JOIN public.customers c ON c.id = o.customer_id
        WHERE o.status = p_status
        ORDER BY o.ordered_at DESC
        LIMIT 500;
END
$$;

CREATE FUNCTION public.fn_next_order_number()
RETURNS text
LANGUAGE plpgsql VOLATILE
AS $$
BEGIN
    RETURN 'ORD-NEW-' || lpad(nextval('sales.invoice_seq')::text, 8, '0');
END
$$;

CREATE FUNCTION sales.fn_audit_order_status()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO sales.order_audit (order_id, old_status, new_status, changed_at, changed_by)
    VALUES (NEW.id, OLD.status, NEW.status, now(), current_user);
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_orders_audit_status
AFTER UPDATE OF status ON sales.orders
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION sales.fn_audit_order_status();

CREATE PROCEDURE analytics.proc_refresh_dashboard()
LANGUAGE plpgsql
AS $$
BEGIN
    REFRESH MATERIALIZED VIEW analytics.mv_daily_events;
    ANALYZE analytics.mv_daily_events;
    RAISE NOTICE 'refreshed analytics.mv_daily_events';
END
$$;

COMMENT ON FUNCTION analytics.fn_customer_lifetime(bigint) IS 'Total order value for a customer';
COMMENT ON FUNCTION analytics.fn_orders_by_status(public.order_status) IS 'Returns most recent orders for a status (TABLE-returning)';
COMMENT ON PROCEDURE analytics.proc_refresh_dashboard() IS 'Refreshes the analytics materialized view';

