CREATE TYPE public.customer_status AS ENUM ('active', 'inactive', 'vip', 'churned');
CREATE TYPE public.order_status AS ENUM ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded');
CREATE TYPE public.payment_method AS ENUM ('card', 'paypal', 'bank_transfer', 'crypto', 'gift_card');
CREATE TYPE public.product_category AS ENUM ('electronics', 'clothing', 'books', 'home', 'sports', 'toys', 'food', 'beauty');
COMMENT ON TYPE public.order_status IS 'Lifecycle of an order';

CREATE DOMAIN public.email_address AS text
  CONSTRAINT email_address_format CHECK (VALUE ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$');
CREATE DOMAIN public.positive_money AS numeric(14,2)
  CONSTRAINT positive_money_non_negative CHECK (VALUE >= 0);

