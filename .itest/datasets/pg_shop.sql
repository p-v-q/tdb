CREATE VIEW reporting.v_customer_order_totals AS
SELECT c.id AS customer_id,
       c.email,
       c.display_name,
       count(o.id) AS order_count,
       coalesce(sum(o.total), 0)::numeric(14,2) AS lifetime_value,
       max(o.ordered_at) AS last_order_at
FROM public.customers c
LEFT JOIN sales.orders o ON o.customer_id = c.id
GROUP BY c.id, c.email, c.display_name;

CREATE VIEW reporting.v_product_sales AS
SELECT p.id AS product_id,
       p.sku,
       p.name,
       p.category,
       sum(oi.quantity) AS units_sold,
       sum(oi.line_total)::numeric(14,2) AS revenue
FROM public.products p
JOIN sales.order_items oi ON oi.product_id = p.id
GROUP BY p.id, p.sku, p.name, p.category;

CREATE VIEW reporting.v_daily_revenue AS
SELECT date_trunc('day', ordered_at) AS day,
       currency,
       count(*) AS order_count,
       sum(total)::numeric(14,2) AS revenue
FROM sales.orders
WHERE status IN ('paid', 'shipped', 'delivered')
GROUP BY 1, 2;

CREATE VIEW reporting.v_low_stock AS
SELECT i.product_id, p.sku, p.name, i.warehouse, i.quantity, i.reorder_level
FROM inventory.inventory i
JOIN public.products p ON p.id = i.product_id
WHERE i.quantity < i.reorder_level;

-- View whose definition exercises constraints (CHECK OPTION + security barrier)
CREATE VIEW reporting.v_active_customers
WITH (security_barrier = true) AS
SELECT id, email, first_name, last_name, display_name, status, balance, created_at
FROM public.customers
WHERE status = 'active' AND balance >= 0
WITH CHECK OPTION;

-- A view restricted by CHECK/UNIQUE semantics of the underlying tables
CREATE VIEW reporting.v_verified_reviews AS
SELECT r.id, r.product_id, p.sku, r.rating, r.title, r.body, r.helpful_votes, r.created_at
FROM public.reviews r
JOIN public.products p ON p.id = r.product_id
WHERE r.rating BETWEEN 1 AND 5
  AND p.price >= 0
  AND length(coalesce(r.title, '')) > 0;

CREATE MATERIALIZED VIEW analytics.mv_daily_events AS
SELECT date_trunc('day', occurred_at) AS day,
       event_type,
       count(*) AS event_count,
       count(DISTINCT session_id) AS session_count
FROM analytics.events
GROUP BY 1, 2
WITH DATA;
CREATE UNIQUE INDEX mv_daily_events_key ON analytics.mv_daily_events (day, event_type);
COMMENT ON MATERIALIZED VIEW analytics.mv_daily_events IS 'Daily event aggregates; refreshed by analytics.proc_refresh_dashboard()';

